def test_列重复渲染的按钮坐标各异且可命中() -> None:
    """这是之前 bug 的直接场景：列表里每个按钮都要能单独点中。"""
    源 = '''
页 "t" 【
  空值 态 项们
  始 【
    [1, 2, 3, 4, 5] 归 项们
  】
  竖 缝 10 填 20 【
    列 项 于 项们 【
      钮 "查看" + 串(项)
    】 缝 10
  】
】
'''
    根 = 布(源, 900, 800)
    盒们 = 绝对盒们(根)
    assert len(盒们) == 5, f"应有 5 个按钮，实际 {len(盒们)}"

    坐标 = [(ax, ay) for _, ax, ay in 盒们]
    assert len(set(坐标)) == 5, f"5 个按钮坐标应各不相同，实际 {坐标}"

    文本们 = []
    for 盒, ax, ay in 盒们:
        命中 = 命中最上层(根, int(ax + 盒["宽"] / 2), int(ay + 盒["高"] / 2))
        assert 命中 is 盒, f"「{盒.get('文本')}」中心命中了别的元素"
        文本们.append(盒.get("文本"))

    assert 文本们 == ["查看1", "查看2", "查看3", "查看4", "查看5"]


