"""命中测试回归测试。

背景：曾经有一个严重 bug —— 布局产出的盒坐标是「相对父容器」的，
但命中测试直接拿它和鼠标的绝对坐标比较，导致：
  · 点「登录」按钮却命中「技术」按钮
  · 列表里 7 个「查看」按钮坐标完全相同，只有第一个可能被点中

这些测试守住「每个可点击元素的中心点必须命中自己」。
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

根目录 = Path(__file__).resolve().parent.parent.parent.parent
sys.path.insert(0, str(根目录))

from 爻页.布局 import 布局, 命中最上层, 遍历
from 爻页.求值 import 求值器
from 爻页.语法 import 分析文本


def 布(源: str, 宽: int = 900, 高: int = 800) -> dict:
    页 = 分析文本(源)
    状态 = {}
    for d in 页.态:
        状态[d.名] = 求值器(状态).求值(d.值)
    求 = 求值器(状态)
    if 页.始 is not None:
        求.允许新建 = True
        try:
            求.执行块(页.始)
        finally:
            求.允许新建 = False
    return 布局(页, 求, 宽, 高)


def 绝对盒们(根: dict):
    """返回所有可点击盒及其绝对坐标。"""
    出 = []

    def 走(b: dict, px: float, py: float) -> None:
        ax, ay = px + b["x"], py + b["y"]
        if b["类"] in ("钮", "输"):
            出.append((b, ax, ay))
        for c in b.get("子", []):
            走(c, ax, ay)

    走(根, 0.0, 0.0)
    return 出


