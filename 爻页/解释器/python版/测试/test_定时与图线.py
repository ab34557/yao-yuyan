def 布(源: str, 宽: int = 900, 高: int = 700) -> tuple[dict, 求值器]:
    页 = 分析文本(源)
    状态 = {}
    for d in 页.态:
        状态[d.名] = 求值器(状态).求值(d.值)
    求 = 求值器(状态)
    for f in (getattr(页, "函数们", None) or []):
        求.函数表[f.名] = f
    if 页.始 is not None:
        求.允许新建 = True
        try:
            求.执行块(页.始)
        finally:
            求.允许新建 = False
    return 布局(页, 求, 宽, 高), 求


