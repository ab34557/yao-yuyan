def test_图线解析与布局() -> None:
    根盒, _ = 布(
        '页 "t" 【\n'
        '  [3, 1, 4, 1, 5, 9, 2, 6] 态 数据\n'
        '  竖 填 10 【\n'
        '    图线 数据 宽 满 高 120 色 "#7ee787" 底线 "#1e293b" 点色 "#fbbf24"\n'
        '  】\n'
        '】'
    )
    图线们 = [b for b in 遍历(根盒) if b["类"] == "图线"]
    assert len(图线们) == 1
    盒 = 图线们[0]
    assert 盒["高"] == 120.0
    assert 盒["数据"] == [3.0, 1.0, 4.0, 1.0, 5.0, 9.0, 2.0, 6.0]
    assert 盒["式"]["色"] == "#7ee787"
    assert 盒["式"]["底线"] == "#1e293b"
    assert 盒["式"]["点色"] == "#fbbf24"


