def test_定时器真实触发() -> None:
    """用真实 tkinter 事件循环验证定时器会反复执行。"""
    tk = pytest.importorskip("tkinter")

    from 爻页.浏览器 import 浏览器

    临时 = 根目录 / "build" / "_定时验证.页"
    临时.parent.mkdir(exist_ok=True)
    临时.write_text(
        '页 "定时验证" 【\n'
        '  0 态 计数\n'
        '  次 100 毫秒 【 置 计数 计数 + 1 】\n'
        '  文 串(计数) 大 20\n'
        '】',
        encoding="utf-8",
        newline="\n",
    )
    try:
        根窗 = tk.Tk()
        根窗.geometry("400x300")
        浏 = 浏览器(根窗, 初始页=str(临时))
        根窗.update()
        初 = 浏.求值器.状态.get("计数", 0)
        截止 = time.time() + 0.9
        while time.time() < 截止:
            根窗.update()
            time.sleep(0.02)
        后 = 浏.求值器.状态.get("计数", 0)
        根窗.destroy()
        assert 后 > 初, f"定时器未触发：{初} → {后}"
    finally:
        临时.unlink(missing_ok=True)
