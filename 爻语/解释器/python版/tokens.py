@dataclass(slots=True)
class 词:
    """一个词法单元。"""

    类: str
    """类别：数 / 字 / 名 / 键 / 符 / 块起 / 块止 / 换行 / 文件止"""
    文: Any
    """字面值或符号文本。"""
    行: int
    列: int
    原: str = ""
    """原始文本（用于报错与 IDE 高亮）。"""

    def __repr__(self) -> str:  # pragma: no cover - 调试用
        return f"词({self.类}, {self.文!r}, {self.行}:{self.列})"


