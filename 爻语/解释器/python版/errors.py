"""爻语错误体系：所有面向用户的报错都是中文。

报错格式（SPEC 6.2）：

    第 3 行 第 5 列：名误：没有此名字「甲」
      在 匠 算账(主.yao:12) 调用处
"""

from __future__ import annotations

from typing import Any


class 爻误(Exception):
    """所有爻语运行时/编译期错误的基类。"""

    类 = "误"
    默认文 = "未知错误"

    def __init__(
        self,
        文: str | None = None,
        行: int = 0,
        列: int = 0,
        值: Any = None,
    ) -> None:
        self.文 = 文 or self.默认文
        self.行 = 行
        self.列 = 列
        self.值 = 值
        self.栈: list[str] = []
        super().__init__(self.格式化())

    # -- 展示 ---------------------------------------------------------------

    def 加栈(self, 帧: str) -> None:
        self.栈.append(帧)

    def 头部(self) -> str:
        if self.行:
            return f"第 {self.行} 行 第 {self.列} 列：{self.类}：{self.文}"
        return f"{self.类}：{self.文}"

    def 格式化(self) -> str:
        行们 = [self.头部()]
        for 帧 in self.栈:
            行们.append(f"  {帧}")
        return "\n".join(行们)

    def 成表(self) -> dict[str, Any]:
        return {
            "类": self.类,
            "文": self.格式化(),
            "行": self.行,
            "列": self.列,
            "栈": list(self.栈),
        }

    def __str__(self) -> str:  # 便于直接 print
        return self.格式化()


