def 造错(类名: str, 文: str, 行: int = 0, 列: int = 0) -> 爻误:
    """按中文类名创建错误对象。"""
    映射 = {
        "词误": 词误,
        "法误": 法误,
        "名误": 名误,
        "型误": 型误,
        "值误": 值误,
        "零误": 零误,
        "键误": 键误,
        "核误": 核误,
        "抛误": 抛误,
        "引误": 引误,
        "网误": 网误,
        "时误": 时误,
        "限误": 限误,
        "内误": 内误,
    }
    根 = 映射.get(类名, 爻误)
    return 根(文, 行, 列)
